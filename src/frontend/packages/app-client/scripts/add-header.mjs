// SPDX-License-Identifier: AGPL-3.0-only
// Puts the licence header on the generated schema, so the SPDX check covers generated code too.
import { readFileSync, writeFileSync } from "node:fs";

const path = new URL("../src/schema.ts", import.meta.url);
const header = "// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by openapi-typescript from openapi.json (pnpm run generate). Do not edit.\n";
const content = readFileSync(path, "utf8");

if (!content.startsWith(header)) {
  writeFileSync(path, header + content);
}
