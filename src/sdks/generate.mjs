const resources = ["surveys", "responses", "exports", "webhooks", "users", "participants"];
const skipped = new Set(["Stream", "TokenResponse", "TokenError"]);
const header = "Generated by src/sdks/generate.mjs from docs/api/openapi.json. Do not edit; run the generator.";

// ---- the model: schemas and operations, language-neutral ----

const refName = (ref) => ref.split("/").pop();

/** A type as { kind, nullable, ... }: ref, string, uuid, date, int, long, number, bool, array, binary. */
function typeOf(schema) {
  if (schema.$ref) return { kind: "ref", name: refName(schema.$ref), nullable: false };
  if (schema.oneOf) {
    const inner = schema.oneOf.find((each) => each.type !== "null");
    return { ...typeOf(inner), nullable: schema.oneOf.some((each) => each.type === "null") };
  }
  const types = [schema.type].flat();
  const nullable = types.includes("null");
  if (types.includes("array")) return { kind: "array", of: typeOf(schema.items), nullable };
  if (types.includes("integer")) return { kind: schema.format === "int64" ? "long" : "int", nullable };
  if (types.includes("number")) return { kind: "number", nullable };
  if (types.includes("boolean")) return { kind: "bool", nullable };
  if (schema.format === "binary") return { kind: "binary", nullable };
  if (schema.format === "uuid") return { kind: "uuid", nullable };
  if (schema.format === "date-time") return { kind: "date", nullable };
  return { kind: "string", nullable };
}

const schemas = Object.entries(api.components.schemas)
  .filter(([name]) => !skipped.has(name))
  .map(([name, schema]) => ({
    name,
    description: schema.description ?? name,
    properties: Object.entries(schema.properties ?? {}).map(([prop, value]) => ({
      name: prop,
      description: value.description ?? prop,
      type: typeOf(value),
      required: (schema.required ?? []).includes(prop),
    })),
  }));
const byName = new Map(schemas.map((schema) => [schema.name, schema]));

const operations = [];
for (const [path, item] of Object.entries(api.paths)) {
  for (const [method, op] of Object.entries(item)) {
    const key = `${method.toUpperCase()} ${path}`;
    if (!(key in names)) throw new Error(`Name ${key} in src/sdks/generate.mjs`);
    if (names[key] === null) continue;
    const [resource, name] = names[key];
    const parameters = op.parameters ?? [];
    const success = Object.entries(op.responses).find(([status]) => status.startsWith("2"));
    const content = success[1].content ?? {};
    const json = content["application/json"]?.schema;
    const result = content["application/octet-stream"] ? { kind: "binary" } : json?.$ref ? typeOf(json) : null;
    const body = op.requestBody?.content?.["application/json"]?.schema;
    // A cursor is opaque to callers, whatever its format.
    const query = parameters.filter((each) => each.in === "query").map((each) => ({ name: each.name, description: each.description ?? each.name, type: each.name === "cursor" ? { kind: "string", nullable: false } : typeOf(each.schema) }));
    const resultSchema = result?.kind === "ref" ? byName.get(result.name) : undefined;
    const has = (prop) => resultSchema?.properties.some((each) => each.name === prop);
    const itemsOf = () => resultSchema.properties.find((each) => each.name === "items").type.of;
    operations.push({
      resource,
      name,
      method: method.toUpperCase(),
      path,
      summary: op.summary ?? name,
      description: op.description ?? "",
      pathParams: parameters.filter((each) => each.in === "path").map((each) => ({ name: each.name, description: each.description ?? each.name, type: typeOf(each.schema) })),
      query,
      idempotent: parameters.some((each) => each.in === "header" && each.name === "Idempotency-Key"),
      body: body ? typeOf(body) : null,
      result,
      // Paging: a cursor (nextCursor) or a sequence (nextSince) gives an "all" variant that walks every page.
      paging: has("nextCursor") && query.some((each) => each.name === "cursor") ? { by: "cursor", items: itemsOf() } : has("nextSince") && query.some((each) => each.name === "since") ? { by: "since", items: itemsOf() } : null,
    });
  }
}

const pascal = (text) => text.replace(/(^|[_-])([a-z])/g, (_, __, letter) => letter.toUpperCase());
const camel = (text) => pascal(text).replace(/^./, (letter) => letter.toLowerCase());
const snake = (text) => text.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`).replace(/-/g, "_");
const oneLine = (text) => text.replace(/\s+/g, " ").trim();
const pathWith = (path, each) => path.replace(/\{(\w+)\}/g, (_, name) => each(name));

// ---- TypeScript ----

function ts(type) {
  const base = { ref: type.name, string: "string", uuid: "string", date: "string", int: "number", long: "number", number: "number", bool: "boolean", binary: "Uint8Array" }[type.kind] ?? `${ts({ ...type.of, nullable: type.of.nullable })}[]`;
  const wrapped = type.kind === "array" && type.of.nullable ? `(${ts(type.of)})[]` : base;
  return type.nullable ? `${wrapped} | null` : wrapped;
}

function typescript() {
  const out = [`// SPDX-License-Identifier: Apache-2.0`, `// ${header}`, `import type { Transport } from "./transport.ts";`, ""];
  for (const schema of schemas) {
    out.push(`/** ${oneLine(schema.description)} */`, `export interface ${schema.name} {`);
    for (const prop of schema.properties) out.push(`  /** ${oneLine(prop.description)} */`, `  ${prop.name}${prop.required ? "" : "?"}: ${ts(prop.type)};`);
    out.push("}", "");
  }
  for (const resource of resources) {
    out.push(`/** ${pascal(resource)} in the Public API. */`, `export class ${pascal(resource)}Api {`, "  readonly #t: Transport;", "", "  constructor(transport: Transport) {", "    this.#t = transport;", "  }");
    for (const op of operations.filter((each) => each.resource === resource)) {
      const params = op.pathParams.map((each) => `${each.name}: string`);
      if (op.body) params.push(`body: ${ts(op.body)}`);
      const options = [...op.query.map((each) => `${each.name}?: ${ts({ ...each.type, nullable: false })}`), ...(op.idempotent ? ["idempotencyKey?: string"] : [])];
      if (options.length > 0) params.push(`options: { ${options.join("; ")} } = {}`);
      const result = op.result ? ts(op.result) : "void";
      const url = "`" + pathWith(op.path, (name) => `\${encodeURIComponent(${name})}`) + "`";
      const args = op.query.length > 0 ? [`query: { ${op.query.map((each) => `${each.name}: options.${each.name}`).join(", ")} }`] : [];
      if (op.body) args.push("body");
      if (op.idempotent) args.push("idempotencyKey: options.idempotencyKey ?? crypto.randomUUID()");
      if (op.result?.kind === "binary") args.push("binary: true");
      out.push("", `  /** ${oneLine(op.summary)} ${oneLine(op.description)} */`, `  ${op.name}(${params.join(", ")}): Promise<${result}> {`, `    return this.#t.request("${op.method}", ${url}, { ${args.join(", ")} }) as Promise<${result}>;`, "  }");
      if (op.paging) {
        const pageParams = op.pathParams.map((each) => `${each.name}: string`);
        const pageOptions = op.query.filter((each) => each.name !== "cursor").map((each) => `${each.name}?: ${ts({ ...each.type, nullable: false })}`);
        pageParams.push(`options: { ${pageOptions.join("; ")} } = {}`);
        const call = (value) => `this.${op.name}(${[...op.pathParams.map((each) => each.name), `{ ...options, ${value} }`].join(", ")})`;
        const walk = op.paging.by === "cursor" ? `this.#t.byCursor((cursor) => ${call("cursor")})` : `this.#t.bySequence(options.since ?? 0, (since) => ${call("since")})`;
        out.push("", `  /** Every item of ${op.name}, page after page. */`, `  ${op.name}All(${pageParams.join(", ")}): AsyncIterable<${ts(op.paging.items)}> {`, `    return ${walk};`, "  }");
      }
    }
    out.push("}", "");
  }
  return out.join("\n");
}

// ---- C# ----

function cs(type) {
  const base = { ref: type.name, string: "string", uuid: "Guid", date: "DateTimeOffset", int: "int", long: "long", number: "double", bool: "bool", binary: "byte[]" }[type.kind] ?? `IReadOnlyList<${cs(type.of)}>`;
  return type.nullable ? `${base}?` : base;
}

const csDefault = (type) => (type.nullable ? "" : { ref: " = new();", string: ' = "";', array: " = [];" }[type.kind] ?? "");
const xml = (text) => oneLine(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function csharp() {
  const out = [`// SPDX-License-Identifier: Apache-2.0`, `// ${header}`, "using System.Text.Json.Serialization;", "", "namespace Askwerk.Sdk;", ""];
  for (const schema of schemas) {
    out.push(`/// <summary>${xml(schema.description)}</summary>`, `public sealed class ${schema.name}`, "{");
    schema.properties.forEach((prop, index) => {
      const type = prop.required ? prop.type : { ...prop.type, nullable: true };
      if (index > 0) out.push("");
      out.push(`    /// <summary>${xml(prop.description)}</summary>`, `    [JsonPropertyName("${prop.name}")]`, `    public ${cs(type)} ${pascal(prop.name)} { get; init; }${csDefault(type)}`);
    });
    out.push("}", "");
  }
  for (const resource of resources) {
    out.push(`/// <summary>${pascal(resource)} in the Public API.</summary>`, `public sealed partial class ${pascal(resource)}Api`, "{", "    private readonly Transport _t;", "", `    internal ${pascal(resource)}Api(Transport transport)`, "    {", "        _t = transport;", "    }");
    for (const op of operations.filter((each) => each.resource === resource)) {
      const params = op.pathParams.map((each) => `${cs(each.type)} ${each.name}`);
      if (op.body) params.push(`${cs(op.body)} body`);
      params.push(...op.query.map((each) => `${cs({ ...each.type, nullable: true })} ${each.name} = null`));
      if (op.idempotent) params.push("string? idempotencyKey = null");
      params.push("CancellationToken cancellationToken = default");
      const result = op.result ? cs(op.result) : null;
      const url = "$\"" + pathWith(op.path, (name) => `{${name}}`) + "\"";
      const query = op.query.length > 0 ? `[${op.query.map((each) => `("${each.name}", ${each.name})`).join(", ")}]` : "[]";
      const args = [`HttpMethod.${pascal(op.method.toLowerCase())}`, url, query, op.body ? "body" : "null", op.idempotent ? "idempotencyKey ?? Guid.NewGuid().ToString()" : "null", "cancellationToken"];
      const call = result === "byte[]" ? `_t.SendForBytesAsync(${args.join(", ")})` : result ? `_t.SendAsync<${result}>(${args.join(", ")})` : `_t.SendAsync(${args.join(", ")})`;
      out.push("", `    /// <summary>${xml(op.summary)}</summary>`, ...(op.description ? [`    /// <remarks>${xml(op.description)}</remarks>`] : []), `    public Task${result ? `<${result}>` : ""} ${pascal(op.name)}Async(${params.join(", ")}) =>`, `        ${call};`);
      if (op.paging) {
        const kept = op.query.filter((each) => each.name !== "cursor");
        const pageParams = [...op.pathParams.map((each) => `${cs(each.type)} ${each.name}`), ...kept.map((each) => `${cs({ ...each.type, nullable: true })} ${each.name} = null`), "CancellationToken cancellationToken = default"];
        const pass = (value) => [...op.pathParams.map((each) => each.name), ...op.query.map((each) => (each.name === op.paging.by ? value : each.name)), "cancellationToken: cancellationToken"].join(", ");
        const walk =
          op.paging.by === "cursor"
            ? `Transport.ByCursorAsync(cursor => ${pascal(op.name)}Async(${pass("cursor")}), page => page.Items, page => page.NextCursor, cancellationToken)`
            : `Transport.BySequenceAsync(since ?? 0, next => ${pascal(op.name)}Async(${pass("next")}), page => page.Items, page => page.NextSince, cancellationToken)`;
        out.push("", `    /// <summary>Every item of ${pascal(op.name)}Async, page after page.</summary>`, `    public IAsyncEnumerable<${cs(op.paging.items)}> ${pascal(op.name)}AllAsync(${pageParams.join(", ")}) =>`, `        ${walk};`);
      }
    }
    out.push("}", "");
  }
  return out.join("\n");
}

// ---- Python ----

function py(type) {
  const base = { ref: `"${type.name}"`, string: "str", uuid: "str", date: "str", int: "int", long: "int", number: "float", bool: "bool", binary: "bytes" }[type.kind] ?? `list[${py(type.of)}]`;
  return type.nullable ? `${base} | None` : base;
}

const keywords = new Set(["from", "import", "class", "def", "global", "lambda", "pass", "return", "in", "is", "not", "and", "or", "if", "else", "for", "while", "with", "as", "try", "except", "raise", "del", "yield", "async", "await", "None", "True", "False"]);

function python() {
  const out = [`# SPDX-License-Identifier: Apache-2.0`, `# ${header}`, "from __future__ import annotations", "", "import uuid", "from collections.abc import Iterator", "from typing import TYPE_CHECKING, NotRequired, TypedDict", "", "if TYPE_CHECKING:", "    from ._transport import Transport", ""];
  for (const schema of schemas) {
    const field = (prop) => (prop.required ? py(prop.type) : `NotRequired[${py(prop.type)}]`);
    if (schema.properties.some((prop) => keywords.has(prop.name))) {
      // A key that is a Python keyword (e.g. "from") needs the functional form.
      out.push("", `${schema.name} = TypedDict("${schema.name}", {`, ...schema.properties.map((prop) => `    "${prop.name}": ${field(prop)},`), "})", `"""${oneLine(schema.description)}"""`, "");
      continue;
    }
    out.push("", `class ${schema.name}(TypedDict):`, `    """${oneLine(schema.description)}"""`, "");
    for (const prop of schema.properties) out.push(`    ${prop.name}: ${field(prop)}`, `    """${oneLine(prop.description)}"""`);
    out.push("");
  }
  for (const resource of resources) {
    out.push("", `class ${pascal(resource)}Api:`, `    """${pascal(resource)} in the Public API."""`, "", "    def __init__(self, transport: Transport) -> None:", "        self._t = transport");
    for (const op of operations.filter((each) => each.resource === resource)) {
      const params = ["self", ...op.pathParams.map((each) => `${snake(each.name)}: str`)];
      if (op.body) params.push(`body: ${py(op.body)}`);
      const keywords = [...op.query.map((each) => `${snake(each.name)}: ${py({ ...each.type, nullable: true })} = None`), ...(op.idempotent ? ["idempotency_key: str | None = None"] : [])];
      if (keywords.length > 0) params.push("*", ...keywords);
      const result = op.result ? py(op.result).replace(/"/g, "") : "None";
      const url = (op.pathParams.length > 0 ? 'f"' : '"') + pathWith(op.path, (name) => `{${snake(name)}}`) + '"';
      const args = [`"${op.method}"`, url, ...(op.query.length > 0 ? [`query={${op.query.map((each) => `"${each.name}": ${snake(each.name)}`).join(", ")}}`] : [])];
      if (op.body) args.push("body=body");
      if (op.idempotent) args.push("idempotency_key=idempotency_key or str(uuid.uuid4())");
      if (op.result?.kind === "binary") args.push("binary=True");
      out.push("", `    def ${snake(op.name)}(${params.join(", ")}) -> ${result}:`, `        """${oneLine(op.summary)} ${oneLine(op.description)}"""`, `        return self._t.request(${args.join(", ")})  # type: ignore[no-any-return]`);
      if (op.paging) {
        const kept = op.query.filter((each) => each.name !== "cursor");
        const pageParams = ["self", ...op.pathParams.map((each) => `${snake(each.name)}: str`), "*", ...kept.map((each) => `${snake(each.name)}: ${py({ ...each.type, nullable: true })} = None`)];
        const pass = (value) => [...op.pathParams.map((each) => snake(each.name)), ...op.query.map((each) => `${snake(each.name)}=${each.name === op.paging.by ? value : snake(each.name)}`)].join(", ");
        const walk = op.paging.by === "cursor" ? `self._t.by_cursor(lambda cursor: self.${snake(op.name)}(${pass("cursor")}))` : `self._t.by_sequence(since or 0, lambda next_: self.${snake(op.name)}(${pass("next_")}))`;
        out.push("", `    def ${snake(op.name)}_all(${pageParams.join(", ")}) -> Iterator[${py(op.paging.items).replace(/"/g, "")}]:`, `        """Every item of ${snake(op.name)}, page after page."""`, `        return ${walk}  # type: ignore[no-any-return]`);
      }
    }
    out.push("");
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n\n").replace(/^\n+/, "") ;
}

// ---- write or check ----

const files = {
  "typescript/src/generated.ts": typescript(),
  "csharp/Askwerk.Sdk/Generated.cs": csharp(),
  "python/askwerk/_generated.py": python(),
};

const check = process.argv.includes("--check");
const stale = [];
for (const [file, text] of Object.entries(files)) {
  const target = join(here, file);
  if (check) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // a missing file is stale
    }
    if (current !== text) stale.push(file);
  } else {
    writeFileSync(target, text);
  }
}

if (stale.length > 0) {
  console.error(`Stale SDK files (run node src/sdks/generate.mjs): ${stale.join(", ")}`);
  process.exit(1);
}
